import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync('dist/index.html','utf8'),css=readFileSync('dist/assets/home-editorial.css','utf8');
assert.ok(html.includes('class="cm-home-editorial"'),'Editorial home required');
assert.ok(!html.includes('track-statement-contact')&&!html.includes('src="/assets/home-motion-v5.js"'),'Do not reintroduce scroll-scrubbing');
for(const id of ['hero','kompetenzen','arbeiten','ansatz','branchen','journal','fragen','kontakt-abschluss','kontakt'])assert.ok(html.includes('id="'+id+'"'),id+' missing');
assert.equal((html.match(/<h1\b/g)||[]).length,1);
assert.equal((html.match(/id="cm-global-footer"/g)||[]).length,1);
assert.ok(html.indexOf('id="cm-global-footer"')>html.indexOf('</main>'));
assert.equal((html.match(/<img src="\/assets\/portfolio\//g)||[]).length,6);
assert.ok(html.includes('fetchpriority="high"')&&html.includes('srcset=')&&html.includes('loading="lazy"'));
assert.ok(html.includes('class="axes"')&&html.includes('cm-hero-ticker'));
assert.ok(css.includes('@media(max-width:780px)')&&css.includes('grid-template-columns:1fr'));
console.log('PASS homepage editorial flow, preserved anchors, portfolio images, responsive grid, brand signature and global footer.');
