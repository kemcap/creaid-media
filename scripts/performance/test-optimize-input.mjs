import assert from 'node:assert/strict';
import { mkdtempSync,mkdirSync,writeFileSync,readFileSync,existsSync,rmSync } from 'node:fs';
import { join,resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createRequire } from 'node:module';
import { runInNewContext } from 'node:vm';
import { optimizeInput } from './optimize-input.mjs';
import { buildPerformance } from './engine.mjs';
const toolRoot=process.argv[2];
if(!toolRoot)throw Error('Pass isolated optimizer tool directory');
const sharp=createRequire(join(resolve(toolRoot),'package.json'))('sharp');
const root=mkdtempSync(join(tmpdir(),'creaid-opt-'));
try{
  const source=join(root,'dist');
  mkdirSync(join(source,'assets'),{recursive:true});
  const css='body {\n    color: #111;\n    background: url("./photo.png");\n}\n';
  const js='"use strict";\nfunction  showMessage  (name) {\n  return  "Hello " + name;\n}\n globalThis.result = showMessage("CreAid");\n';
  const image=await sharp({create:{width:200,height:100,channels:4,background:{r:20,g:80,b:120,alpha:0.5}}}).png({compressionLevel:0}).toBuffer();
  const html='<html><head><link rel="stylesheet" href="/assets/main.css"></head><body><img src="/assets/photo.png"><script src="/assets/app.js"></script></body></html>';
  for(const [p,b] of [['index.html',html],['assets/main.css',css],['assets/app.js',js],['assets/photo.png',image]])writeFileSync(join(source,p),b);
  const config={files:['assets/main.css','assets/app.js','assets/photo.png']};
  const output=join(root,'optimized');
  const result=await optimizeInput({source,output,config,toolRoot});
  assert.equal(result.selected,3);
  assert.equal(result.changed,3);
  assert.ok(result.savedBytes>0);
  const site=join(output,'site');
  assert.equal(readFileSync(join(source,'assets/main.css'),'utf8'),css);
  assert.equal(readFileSync(join(source,'assets/app.js'),'utf8'),js);
  assert.deepEqual(readFileSync(join(source,'assets/photo.png')),image);
  assert.equal(readFileSync(join(site,'index.html'),'utf8'),html);
  assert.match(readFileSync(join(site,'assets/main.css'),'utf8'),/photo\.png/);
  const a={},b={};runInNewContext(js,a);runInNewContext(readFileSync(join(site,'assets/app.js'),'utf8'),b);
  assert.equal(a.result,b.result);
  assert.deepEqual(await sharp(image).raw().toBuffer(),await sharp(readFileSync(join(site,'assets/photo.png'))).raw().toBuffer());
  const engine=buildPerformance({source:site,output:join(root,'packaged')});
  assert.equal(engine.verifiedAssets,3);
  await assert.rejects(optimizeInput({source,output:join(source,'bad'),config,toolRoot}),/isolated/);
  await assert.rejects(optimizeInput({source,output:join(root,'bad'),config:{files:['assets/../index.html']},toolRoot}),/Unsafe/);
  writeFileSync(join(source,'index.html'),html.replace('rel="stylesheet"','rel="stylesheet" integrity="sha256-example"'));
  const guarded=await optimizeInput({source,output:join(root,'sri'),config:{files:['assets/main.css','assets/app.js']},toolRoot});
  assert.equal(guarded.changed,0);
  assert.ok(guarded.rows.every(r=>r.reason==='sri-present-preserved'));
  assert.equal(existsSync(join(root,'bad')),false);
  console.log('PASS: CSS/JS minification, pixel-identical PNG, SRI gate, isolated source, optimization-before-fingerprinting');
}finally{rmSync(root,{recursive:true,force:true});}
