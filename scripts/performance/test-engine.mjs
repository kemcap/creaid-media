import assert from 'node:assert/strict';
import { mkdtempSync,mkdirSync,writeFileSync,readFileSync,rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { apachePolicy,buildPerformance,verifyCandidate } from './engine.mjs';
const root=mkdtempSync(join(tmpdir(),'creaid-engine-'));
try {
  const source=join(root,'dist');mkdirSync(join(source,'assets'),{recursive:true});
  const html='<html><head><link rel="stylesheet" href="/assets/style.css"></head><body><img src="/assets/a.webp"><script src="/assets/app.js"></script></body></html>';
  writeFileSync(join(source,'index.html'),html);
  writeFileSync(join(source,'assets/style.css'),'body{background:url(a.webp)}');
  writeFileSync(join(source,'assets/app.js'),'console.log("test")');
  writeFileSync(join(source,'assets/a.webp'),'fixture');
  writeFileSync(join(source,'.htaccess'),'DirectoryIndex index.html\n');
  const output=join(root,'preview');
  const report=buildPerformance({source,output});
  assert.equal(report.verifiedAssets,3);
  assert.equal(report.profile,'preview');
  const preview=readFileSync(join(output,'site','.htaccess'),'utf8');
  assert.ok(preview.includes('DirectoryIndex index.html'));
  assert.ok(preview.includes('no-store'));
  assert.ok(!preview.includes('immutable'));
  assert.equal(readFileSync(join(source,'index.html'),'utf8'),html);
  assert.equal(readFileSync(join(source,'.htaccess'),'utf8'),'DirectoryIndex index.html\n');
  assert.throws(()=>buildPerformance({source,output:join(root,'noapproval'),profile:'production'}),/approval/);
  const prod=buildPerformance({source,output:join(root,'production'),profile:'production',approved:true});
  assert.equal(prod.verifiedAssets,3);
  assert.match(apachePolicy('production'),/immutable/);
  assert.match(apachePolicy('production'),/REQUEST_STATUS/);
  assert.match(apachePolicy('production'),/DEFLATE/);
  assert.throws(()=>buildPerformance({source,output}),/isolated|new isolated/);
  assert.throws(()=>buildPerformance({source,output:join(source,'bad')}),/isolated/);
  const asset=join(output,'site',report.manifest[0].fingerprinted.slice(1));
  writeFileSync(asset,'tampered');
  assert.throws(()=>verifyCandidate(output,report),/mismatch/);
  writeFileSync(join(source,'index.html'),'<meta name="robots" content="noindex">'+html);
  assert.throws(()=>buildPerformance({source,output:join(root,'blocked'),profile:'production',approved:true}),/Preview/);
  writeFileSync(join(source,'index.html'),html);
  writeFileSync(join(source,'robots.txt'),'User-agent: *\nDisallow: /\n');
  assert.throws(()=>buildPerformance({source,output:join(root,'blocked2'),profile:'production',approved:true}),/robots/);
  writeFileSync(join(source,'.htaccess'),'Header set Cache-Control "public"\n');
  assert.throws(()=>buildPerformance({source,output:join(root,'conflict')}),/reconciliation/);
  assert.throws(()=>apachePolicy('invalid'),/Unknown/);
  console.log('PASS: isolated output, preview/production profiles, hash integrity, approval, noindex and robots guards, conflict detection');
} finally {rmSync(root,{recursive:true,force:true});}
